import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { isDataFile } from "../content/data";
import { listDataFiles } from "../content/data.disk";

/**
 * `npm run data:index`: writes `content/data.generated.ts`, one static import
 * per file in `data/`. The server and the Worker load content from it, since a
 * Worker can't scan a folder. Run it after adding, moving or removing a data
 * file (`npm run dev` runs it first). `--check` changes nothing and fails when
 * the index is out of date.
 */
const OUT = fileURLToPath(new URL("../content/data.generated.ts", import.meta.url));

const paths = listDataFiles().filter(isDataFile);
const lines = [
    "// Generated by src/dev/geo-data-index.ts — do not edit. Run `npm run data:index` after adding, moving or removing a data file.",
    "",
    'import type { DataFile } from "./data";',
    ...paths.map((path, index) => `import * as f${index} from "../data/${path.replace(/\.ts$/, "")}";`),
    "",
    "/** Every file in `data/`, in content order. */",
    "export const DATA_FILES: readonly DataFile[] = [",
    ...paths.map((path, index) => `    { path: ${JSON.stringify(path)}, module: f${index} },`),
    "];",
    "",
];
const contents = lines.join("\n");
const current = existsSync(OUT) ? readFileSync(OUT, "utf8") : null;

if (process.argv.includes("--check")) {
    if (current !== contents) {
        console.error("content/data.generated.ts is out of date. Run `npm run data:index`.");
        process.exit(1);
    }
    console.log(`Data index matches data/ (${paths.length} files).`);
} else if (current !== contents) {
    writeFileSync(OUT, contents);
    console.log(`Wrote content/data.generated.ts (${paths.length} files).`);
}
